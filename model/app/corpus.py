LAT = str.maketrans({"а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "х": "x", "у": "y"})
EMOJI = ["🎁", "💰", "🔥", "✅", "😊", "👍", "🙏", "😂", "📞"]


def typo(w):
    if len(w) < 5:
        return w
    i = R.randint(1, len(w) - 3)
    if R.random() < 0.5:
        return w[:i] + w[i + 1] + w[i] + w[i + 2:]
    return w[:i] + w[i + 1:]


def add_noise(text, spam):
    words = text.split(" ")
    out = []
    for w in words:
        if w.startswith("http") or "/" in w:
            out.append(w)
            continue
        if R.random() < 0.04:
            w = typo(w)
        if spam and R.random() < 0.10 and w.isalpha():
            w = w.translate(LAT)            # обфускация: «бесплатно» -> «беcплaтно»
        out.append(w)
    t = " ".join(out)
    if R.random() < 0.12:
        t = t.lower()
    if R.random() < 0.15:
        t = t.replace(".", "").replace(",", "")
    if spam and R.random() < 0.3:
        t = t.replace("!", "!!!")
    if R.random() < (0.30 if spam else 0.10):
        t += " " + R.choice(EMOJI)
    return t


def build(n_spam=540, n_ham=960, label_noise=0.015):
    rows = []
    for _ in range(n_spam):
        rows.append((add_noise(spam_message(), True), 1))
    for _ in range(n_ham):
        rows.append((add_noise(ham_message(), False), 0))
    R.shuffle(rows)
    df = pd.DataFrame(rows, columns=["text", "label"])
    flip = df.sample(frac=label_noise, random_state=1).index     # имитация ошибок разметки
    df.loc[flip, "label"] = 1 - df.loc[flip, "label"]
    return df.drop_duplicates("text").reset_index(drop=True)

